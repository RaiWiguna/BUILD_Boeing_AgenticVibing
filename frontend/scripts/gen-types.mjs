// Generates TypeScript wire types from the frozen public JSON Schemas (contracts/json-schema/public).
// `--check` fails when the committed output drifts from the schemas.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));
const schemaDir = path.resolve(here, '../../contracts/json-schema/public');
const outFile = path.resolve(here, '../src/api/generated/contracts.ts');
const check = process.argv.includes('--check');

const defs = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.json')).sort()) {
  const schema = JSON.parse(readFileSync(path.join(schemaDir, file), 'utf8'));
  const { $defs = {}, ...root } = schema;
  for (const [name, def] of Object.entries($defs)) {
    if (defs[name] && JSON.stringify(defs[name]) !== JSON.stringify(def)) {
      throw new Error(`Conflicting $defs/${name} in ${file}`);
    }
    defs[name] = def;
  }
  defs[root.title] = root;
}

const combined = {
  title: 'ContractIndex',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).sort().map((n) => [n, { $ref: `#/$defs/${n}` }])),
  $defs: defs,
};

const banner = `/* Generated by scripts/gen-types.mjs from contracts/json-schema/public (contract 1.0.0). Do not edit. */`;
const ts = await compile(combined, 'ContractIndex', {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true, semi: true },
});

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== ts) {
    console.error('Generated contract types are out of date. Run `npm run gen:types`.');
    process.exit(1);
  }
  console.log('Contract types up to date.');
} else {
  writeFileSync(outFile, ts);
  console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
}
