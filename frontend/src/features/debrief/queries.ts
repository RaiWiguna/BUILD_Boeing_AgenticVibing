import { keepPreviousData, useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { qk } from '@/api/queryKeys';
import type { ExportFormat, ExportJob } from '@/api/types';
import { useApi } from '@/hooks/useApi';
import { useSessionScope } from '@/hooks/useSessionScope';
import { idemKey, releaseKeys } from '@/lib/idempotency';

/** Journal is read for a brief's as-of in Debrief mode (post-hoc view, never mixed into As-known). */
export function useJournal(asOfMs: number | null) {
  const api = useApi();
  const { sid, runId, scope } = useSessionScope();
  return useQuery({
    queryKey: qk.journal(sid, runId ?? '-', 'DEBRIEF', asOfMs ?? 0),
    queryFn: () => api.getJournal(scope!, { asOfMs: asOfMs!, mode: 'DEBRIEF' }),
    enabled: !!scope && asOfMs != null,
    placeholderData: keepPreviousData,
  });
}

export function useBriefs() {
  const api = useApi();
  const { sid, runId, scope } = useSessionScope();
  return useQuery({ queryKey: qk.briefs(sid, runId ?? '-'), queryFn: () => api.listBriefs(scope!), enabled: !!scope });
}

export function useExportPolicy() {
  const api = useApi();
  const { sid, runId, scope } = useSessionScope();
  return useQuery({ queryKey: qk.exportPolicy(sid, runId ?? '-'), queryFn: () => api.getExportPolicy(scope!), enabled: !!scope });
}

/** Polls only while a job is still preparing. */
export function useExports() {
  const api = useApi();
  const { sid, runId, scope } = useSessionScope();
  return useQuery({
    queryKey: qk.exports(sid, runId ?? '-'),
    queryFn: () => api.listExports(scope!),
    enabled: !!scope,
    refetchInterval: (q) => ((q.state.data as ExportJob[] | undefined)?.some((e) => e.status === 'PREPARING') ? 800 : false),
  });
}

export function useCreateBrief() {
  const api = useApi();
  const qc = useQueryClient();
  const { sid, runId, scope } = useSessionScope();
  return useMutation({
    mutationFn: (asOfMs: number) => api.createBrief(scope!, asOfMs, { idempotencyKey: idemKey(`brief:${sid}:${runId}`, asOfMs) }),
    onSuccess: () => releaseKeys(`brief:${sid}:${runId}`),
    onSettled: () => qc.invalidateQueries({ queryKey: qk.briefs(sid, runId ?? '-') }),
  });
}

export function useCreateExport() {
  const api = useApi();
  const qc = useQueryClient();
  const { sid, runId, scope } = useSessionScope();
  return useMutation({
    mutationFn: (input: { format: ExportFormat; briefId: string | null; includeJournal: boolean; redacted: boolean }) =>
      api.createExport(scope!, input, { idempotencyKey: idemKey(`export:${sid}:${runId}`, input) }),
    onSuccess: () => releaseKeys(`export:${sid}:${runId}`),
    onSettled: () => {
      qc.invalidateQueries({ queryKey: qk.exports(sid, runId ?? '-') });
      qc.invalidateQueries({ queryKey: qk.notifications });
    },
  });
}

/** Downloads a READY export as a local Blob — content is generated by the MOCK adapter. */
export function useDownloadExport() {
  const api = useApi();
  return useMutation({
    mutationFn: async (id: string) => {
      const file = await api.downloadExport(id);
      const url = URL.createObjectURL(new Blob([file.content], { type: file.mime }));
      const a = document.createElement('a');
      a.href = url;
      a.download = file.filename;
      a.rel = 'noopener';
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 1000);
      return file.filename;
    },
  });
}
